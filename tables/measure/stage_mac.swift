// Measurement stage-mac: stage-interface rules of this Mac's Metal device.
//
// - color outputs: for fragment outputs of several types and attachments of several pixel formats, whether the render
//   pipeline is created, and Metal's message when it is not; what an attachment the fragment function writes no
//   output for holds after a draw;
// - varyings: whether a vertex output and a fragment input of the same name and different types link, when the
//   fragment function reads the input and when it does not;
// - the linear [[thread_index_in_threadgroup]] of 3D threadgroups;
// - the [[sample_mask]] input of a fragment function that runs per sample, with 4 samples;
// - a [[depth(any)]] output outside [0, 1] and outside the viewport's depth range, stored in Depth32Float.
//
// The output is TOML on stdout. The results describe this Mac's GPU only.
//
// Build and run: xcrun swiftc -O stage_mac.swift -o stage_mac && ./stage_mac > stage_mac.toml

import Foundation
import Metal

func q(_ s: String) -> String { "\"" + s.replacingOccurrences(of: "\"", with: "\\\"") + "\"" }
func fail(_ s: String) -> Never {
    FileHandle.standardError.write((s + "\n").data(using: .utf8)!)
    exit(1)
}

guard let device = MTLCreateSystemDefaultDevice() else { fail("no Metal device") }
let queue = device.makeCommandQueue()!

func lib(_ src: String) -> MTLLibrary {
    do { return try device.makeLibrary(source: "#include <metal_stdlib>\nusing namespace metal;\n" + src,
                                       options: MTLCompileOptions()) } catch { fail("compile: \(error)") }
}

/// A render pipeline; the error's first line when Metal refuses it.
func pipeline(_ d: MTLRenderPipelineDescriptor) -> (MTLRenderPipelineState?, String) {
    do { return (try device.makeRenderPipelineState(descriptor: d), "created") } catch {
        let m = (error as NSError).localizedDescription.split(separator: "\n").first.map(String.init) ?? ""
        return (nil, "refused: " + m)
    }
}

func target(_ f: MTLPixelFormat, _ w: Int, _ h: Int, samples: Int = 1) -> MTLTexture {
    let d = MTLTextureDescriptor.texture2DDescriptor(pixelFormat: f, width: w, height: h, mipmapped: false)
    d.usage = [.renderTarget, .shaderRead]
    d.storageMode = samples > 1 ? .private : .shared
    if samples > 1 { d.textureType = .type2DMultisample; d.sampleCount = samples }
    return device.makeTexture(descriptor: d)!
}

func draw(_ pass: MTLRenderPassDescriptor, _ body: (MTLRenderCommandEncoder) -> Void) {
    let cb = queue.makeCommandBuffer()!
    let e = cb.makeRenderCommandEncoder(descriptor: pass)!
    body(e)
    e.endEncoding()
    cb.commit()
    cb.waitUntilCompleted()
}

let cover = """
struct V { float4 pos [[position]]; };
vertex V vt(uint vid [[vertex_id]]) {
    V o; float2 p = float2(float((vid << 1) & 2u), float(vid & 2u)); o.pos = float4(p * 2.0f - 1.0f, 0.5f, 1.0f); return o;
}
"""

var out = "# Generated by tables/measure/stage_mac.swift. Do not edit by hand.\n\n[meta]\n"
out += "id = \"stage-mac\"\nscript = \"tables/measure/stage_mac.swift\"\n"
out += "device = \(q(device.name))\nhost = \(q("macOS " + ProcessInfo.processInfo.operatingSystemVersionString))\n"
func caseOut(_ id: String, _ fields: [(String, String)]) {
    out += "\n[[case]]\nid = \(q(id))\n"
    for (k, v) in fields { out += "\(k) = \(v)\n" }
}

// Color outputs.
let outputs: [(String, String)] = [
    ("float", "0.25f"), ("float2", "float2(0.25f)"), ("float3", "float3(0.25f)"), ("float4", "float4(0.25f)"),
    ("half", "0.25h"), ("uint", "7u"), ("uint2", "uint2(7u)"), ("uint4", "uint4(7u)"), ("int", "-7"),
]
let formats: [(String, MTLPixelFormat)] = [
    ("A8Unorm", .a8Unorm), ("R8Unorm", .r8Unorm), ("RG8Unorm", .rg8Unorm), ("B5G6R5Unorm", .b5g6r5Unorm),
    ("RGBA8Unorm", .rgba8Unorm), ("RG11B10Float", .rg11b10Float), ("R32Uint", .r32Uint), ("RGBA32Uint", .rgba32Uint),
    ("RGBA32Sint", .rgba32Sint), ("RGBA32Float", .rgba32Float),
]
let colorLib = lib(cover + outputs.map { "fragment \($0.0) f_\($0.0)(V in [[stage_in]]) { return \($0.1); }\n" }.joined())
for (type, _) in outputs {
    for (fname, f) in formats {
        let d = MTLRenderPipelineDescriptor()
        d.vertexFunction = colorLib.makeFunction(name: "vt")
        d.fragmentFunction = colorLib.makeFunction(name: "f_" + type)
        d.colorAttachments[0].pixelFormat = f
        caseOut("color-\(type)-\(fname)", [("pipeline", q(pipeline(d).1))])
    }
}
do {
    let l = lib(cover + "fragment uint4 f(V in [[stage_in]]) { return uint4(1, 2, 3, 4); }\n")
    let d = MTLRenderPipelineDescriptor()
    d.vertexFunction = l.makeFunction(name: "vt")
    d.fragmentFunction = l.makeFunction(name: "f")
    d.colorAttachments[0].pixelFormat = .rgba32Uint
    d.colorAttachments[1].pixelFormat = .rgba32Uint
    let (p, _) = pipeline(d)
    let t0 = target(.rgba32Uint, 4, 4), t1 = target(.rgba32Uint, 4, 4)
    let pass = MTLRenderPassDescriptor()
    for (i, t) in [t0, t1].enumerated() {
        pass.colorAttachments[i].texture = t
        pass.colorAttachments[i].loadAction = .clear
        pass.colorAttachments[i].storeAction = .store
        pass.colorAttachments[i].clearColor = MTLClearColor(red: 5, green: 6, blue: 7, alpha: 8)
    }
    draw(pass) { e in e.setRenderPipelineState(p!); e.drawPrimitives(type: .triangle, vertexStart: 0, vertexCount: 3) }
    var px = [UInt32](repeating: 0, count: 4)
    t1.getBytes(&px, bytesPerRow: 64, from: MTLRegionMake2D(0, 0, 1, 1), mipmapLevel: 0)
    caseOut("color-attachment-without-output", [("cleared_to", "\"5 6 7 8\""),
        ("after_draw", q(px.map(String.init).joined(separator: " ")))])
}

// Varyings: the fragment function reads its input (and, for the last cases, does not).
for (vt, vv, ft, reads) in [("int", "-3", "uint", true), ("uint", "3u", "int", true), ("short", "short(-3)", "ushort", true),
                            ("short", "short(-3)", "int", true), ("char", "char(-3)", "short", true),
                            ("float", "1.5f", "half", true), ("float4", "float4(1)", "float2", true),
                            ("float2", "float2(1)", "float4", true), ("float", "1.5f", "int", true),
                            ("bool", "true", "uint", true), ("float4", "float4(1)", "none", true),
                            ("float", "1.5f", "half", false), ("float4", "float4(1)", "float2", false),
                            ("none", "", "float", true), ("none", "", "float", false)] {
    let fstruct = ft == "none" ? "struct FI { float4 pos [[position]]; };"
        : "struct FI { float4 pos [[position]]; \(ft) x [[user(x)]]; };"
    let lane = ft.last!.isNumber ? "in.x.x" : "in.x"
    let value = ft == "none" || !reads ? "float4(1)" : "float4(float(\(lane)))"
    let vstruct = vt == "none" ? "struct VO { float4 pos [[position]]; };"
        : "struct VO { float4 pos [[position]]; \(vt) x [[user(x)]]; };"
    let set = vt == "none" ? "" : "o.x = \(vv);"
    let l = lib("""
    \(vstruct)
    \(fstruct)
    vertex VO v(uint vid [[vertex_id]]) { VO o; o.pos = float4(0, 0, 0, 1); \(set) return o; }
    fragment float4 f(FI in [[stage_in]]) { return \(value); }
    """)
    let d = MTLRenderPipelineDescriptor()
    d.vertexFunction = l.makeFunction(name: "v")
    d.fragmentFunction = l.makeFunction(name: "f")
    d.colorAttachments[0].pixelFormat = .rgba8Unorm
    let to = ft == "none" ? "no-input" : ft + (reads ? "" : "-unread")
    caseOut("varying-\(vt == "none" ? "no-output" : vt)-to-\(to)", [("pipeline", q(pipeline(d).1))])
}

// The linear thread index of 3D threadgroups.
do {
    let l = lib("""
    kernel void k(device uint *o [[buffer(0)]], uint i [[thread_index_in_threadgroup]],
                  uint3 p [[thread_position_in_threadgroup]], uint3 g [[threadgroup_position_in_grid]],
                  uint3 n [[threads_per_threadgroup]]) {
        uint group = (g.z * 2u + g.y) * 2u + g.x;
        o[group * 512u + (p.z * n.y + p.y) * n.x + p.x] = i + 1u;
    }
    """)
    let p = try! device.makeComputePipelineState(function: l.makeFunction(name: "k")!)
    for s in [(4, 2, 2), (3, 5, 2), (2, 2, 8), (8, 4, 4)] {
        let b = device.makeBuffer(length: 8 * 512 * 4, options: .storageModeShared)!
        let cb = queue.makeCommandBuffer()!
        let e = cb.makeComputeCommandEncoder()!
        e.setComputePipelineState(p)
        e.setBuffer(b, offset: 0, index: 0)
        e.dispatchThreadgroups(MTLSizeMake(2, 2, 2), threadsPerThreadgroup: MTLSizeMake(s.0, s.1, s.2))
        e.endEncoding()
        cb.commit()
        cb.waitUntilCompleted()
        let w = b.contents().bindMemory(to: UInt32.self, capacity: 8 * 512)
        let n = s.0 * s.1 * s.2
        let ok = (0..<8).allSatisfy { g in (0..<n).allSatisfy { w[g * 512 + $0] == UInt32($0 + 1) } }
        caseOut("thread-index-\(s.0)x\(s.1)x\(s.2)", [("threads", "\(8 * n)"),
            ("index_equals_z_sy_plus_y_sx_plus_x", ok ? "true" : "false")])
    }
}

// The coverage-mask input of a function that runs per sample: a triangle covering half of some pixels, 4 samples.
do {
    let l = lib("""
    struct V { float4 pos [[position]]; };
    vertex V v(uint vid [[vertex_id]], constant float2 *p [[buffer(0)]]) { V o; o.pos = float4(p[vid], 0.5f, 1.0f); return o; }
    fragment uint f_pixel(V in [[stage_in]], uint m [[sample_mask]]) { return m; }
    fragment uint f_sample(V in [[stage_in]], uint m [[sample_mask]], uint s [[sample_id]]) { return m; }
    kernel void rd(texture2d_ms<uint, access::read> t [[texture(0)]], device uint *o [[buffer(0)]], uint2 g [[thread_position_in_grid]]) {
        for (uint s = 0; s < 4; s++) o[(g.y * 4 + g.x) * 4 + s] = t.read(g, s).x;
    }
    """)
    let tri: [Float] = [-1, 1, 1, 1, -1, -1]
    let vb = device.makeBuffer(bytes: tri, length: 24)!
    let kp = try! device.makeComputePipelineState(function: l.makeFunction(name: "rd")!)
    for f in ["f_pixel", "f_sample"] {
        let d = MTLRenderPipelineDescriptor()
        d.vertexFunction = l.makeFunction(name: "v")
        d.fragmentFunction = l.makeFunction(name: f)
        d.colorAttachments[0].pixelFormat = .r32Uint
        d.rasterSampleCount = 4
        let (p, _) = pipeline(d)
        let t = target(.r32Uint, 4, 4, samples: 4)
        let pass = MTLRenderPassDescriptor()
        pass.colorAttachments[0].texture = t
        pass.colorAttachments[0].loadAction = .clear
        pass.colorAttachments[0].storeAction = .store
        draw(pass) { e in
            e.setRenderPipelineState(p!)
            e.setVertexBuffer(vb, offset: 0, index: 0)
            e.drawPrimitives(type: .triangle, vertexStart: 0, vertexCount: 3)
        }
        let ob = device.makeBuffer(length: 256, options: .storageModeShared)!
        let cb = queue.makeCommandBuffer()!
        let e = cb.makeComputeCommandEncoder()!
        e.setComputePipelineState(kp)
        e.setTexture(t, index: 0)
        e.setBuffer(ob, offset: 0, index: 0)
        e.dispatchThreadgroups(MTLSizeMake(4, 4, 1), threadsPerThreadgroup: MTLSizeMake(1, 1, 1))
        e.endEncoding()
        cb.commit()
        cb.waitUntilCompleted()
        let w = ob.contents().bindMemory(to: UInt32.self, capacity: 64)
        // Pixels (0, 0) (fully covered) and (3, 0) (on the diagonal, partly covered): the mask each covered sample stored.
        let full = (0..<4).map { String(format: "0x%x", w[$0]) }.joined(separator: " ")
        let part = (0..<4).map { String(format: "0x%x", w[12 + $0]) }.joined(separator: " ")
        caseOut("sample-mask-input-\(f == "f_pixel" ? "per-pixel" : "per-sample")", [
            ("pixel_0_0_samples", q(full)), ("pixel_3_0_samples", q(part))])
    }
}

// Depth outputs.
do {
    let l = lib(cover + """
    struct O { uint c [[color(0)]]; float d [[depth(any)]]; };
    fragment O f(V in [[stage_in]], constant float &d [[buffer(0)]]) { O o; o.c = 1; o.d = d; return o; }
    """)
    let d = MTLRenderPipelineDescriptor()
    d.vertexFunction = l.makeFunction(name: "vt")
    d.fragmentFunction = l.makeFunction(name: "f")
    d.colorAttachments[0].pixelFormat = .r32Uint
    d.depthAttachmentPixelFormat = .depth32Float
    let (p, _) = pipeline(d)
    let dsd = MTLDepthStencilDescriptor()
    dsd.depthCompareFunction = .always
    dsd.isDepthWriteEnabled = true
    let ds = device.makeDepthStencilState(descriptor: dsd)!
    for (value, near, far) in [(Float(1.5), 0.0, 1.0), (-0.5, 0.0, 1.0), (0.9, 0.25, 0.75), (0.1, 0.25, 0.75)] {
        let t = target(.r32Uint, 4, 4)
        let dd = MTLTextureDescriptor.texture2DDescriptor(pixelFormat: .depth32Float, width: 4, height: 4, mipmapped: false)
        dd.usage = [.renderTarget]
        dd.storageMode = .private
        let dt = device.makeTexture(descriptor: dd)!
        let pass = MTLRenderPassDescriptor()
        pass.colorAttachments[0].texture = t
        pass.colorAttachments[0].loadAction = .clear
        pass.colorAttachments[0].storeAction = .store
        pass.depthAttachment.texture = dt
        pass.depthAttachment.loadAction = .clear
        pass.depthAttachment.clearDepth = 0.5
        pass.depthAttachment.storeAction = .store
        var v = value
        draw(pass) { e in
            e.setRenderPipelineState(p!)
            e.setDepthStencilState(ds)
            e.setViewport(MTLViewport(originX: 0, originY: 0, width: 4, height: 4, znear: near, zfar: far))
            e.setFragmentBytes(&v, length: 4, index: 0)
            e.drawPrimitives(type: .triangle, vertexStart: 0, vertexCount: 3)
        }
        let b = device.makeBuffer(length: 64, options: .storageModeShared)!
        let cb = queue.makeCommandBuffer()!
        let bl = cb.makeBlitCommandEncoder()!
        bl.copy(from: dt, sourceSlice: 0, sourceLevel: 0, sourceOrigin: MTLOriginMake(0, 0, 0),
                sourceSize: MTLSizeMake(4, 4, 1), to: b, destinationOffset: 0, destinationBytesPerRow: 16,
                destinationBytesPerImage: 64)
        bl.endEncoding()
        cb.commit()
        cb.waitUntilCompleted()
        let stored = b.contents().bindMemory(to: Float.self, capacity: 16)[0]
        caseOut("depth-output-\(value)-viewport-\(near)-\(far)", [("written", "\(value)"),
            ("viewport_depth_range", q("\(near) \(far)")), ("stored", "\(stored)")])
    }
}

print(out, terminator: "")
