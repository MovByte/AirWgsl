// Threadgroup memory element types, and the pointer types of device, constant and argument-buffer pointers.
let types = ["float", "float4", "int", "uchar", "half2", "S", "float4x4", "atomic_int", "packed_float3", "bool"]
var params = "device uint *out [[buffer(0)]], constant S *c [[buffer(1)]], device AB &ab [[buffer(2)]]"
var body = "out[0] = uint(c->a.x) + uint(*ab.d) + uint(*ab.k);\n"
for (i, t) in types.enumerated() {
    params += ", threadgroup \(t) *t\(i) [[threadgroup(\(i))]]"
    body += "out[\(i + 1)] = uint(sizeof(t\(i)[0])) + (t\(i) != nullptr ? 1 : 0);\n"
}
let src = """
struct S { float4 a; int b; };
struct AB { device float *d; constant int *k; };
kernel void m(\(params)) {
\(body)}
"""
let d = MTLComputePipelineDescriptor()
d.computeFunction = lib(src).makeFunction(name: "m")!
var refl: MTLComputePipelineReflection?
print("")
print("[[case]]")
print("id = \"bindings\"")
do {
    _ = try device.makeComputePipelineState(descriptor: d, options: [.bindingInfo, .bufferTypeInfo],
                                            reflection: &refl)
    for b in refl!.bindings {
        let o = b as AnyObject
        print("[[case.binding]]")
        print("name = \(q(b.name))")
        print("type = \(b.type.rawValue)")
        if b.type == .threadgroupMemory {
            print("threadgroupMemoryDataType = \(value(o, "threadgroupMemoryDataType"))")
        }
        if let bb = b as? MTLBufferBinding, let p = bb.bufferPointerType {
            print("isConstantBuffer = \(value(p as AnyObject, "isConstantBuffer"))")
            if let s = p.elementStructType() {
                for m in s.members {
                    if let mp = m.pointerType() {
                        print("[[case.binding.member]]")
                        print("name = \(q(m.name))")
                        print("isConstantBuffer = \(value(mp as AnyObject, "isConstantBuffer"))")
                    }
                }
            }
        }
    }
} catch {
    print("pipeline = \(q("refused: \((error as NSError).localizedDescription)"))")
}

// The buffers a vertex descriptor and a stage-input descriptor feed, which Metal reports as bindings of their own.
func described(_ id: String, _ list: [MTLBinding]) {
    print("")
    print("[[case]]")
    print("id = \(q(id))")
    for b in list {
        guard let bb = b as? MTLBufferBinding, let p = bb.bufferPointerType else { continue }
        print("[[case.binding]]")
        print("name = \(q(b.name))")
        print("isConstantBuffer = \(value(p as AnyObject, "isConstantBuffer"))")
    }
}
