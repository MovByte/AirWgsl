// Measurement reflect-private: the reflection state Metal's own reflection objects keep beyond the public properties,
// which Metal.framework's initializers take (MTLBuiltInArgument, MTLThreadgroupMemoryBindingInternal,
// MTLPointerTypeInternal):
//
// - built-in arguments: for each kernel and vertex built-in attribute, the AIR key the front end writes for it and the
//   MTLBuiltInArgument the pipeline's reflection lists (name, type, access, isActive, index, builtInType,
//   builtInDataType), for an argument the function reads and one it does not;
// - threadgroup memory: threadgroupMemoryDataType of threadgroup arguments of several element types;
// - pointer address spaces: isConstantBuffer of the pointer types of device and constant buffers, and of pointers in
//   an argument buffer.
//
// The output is TOML on stdout. The results describe this Mac's Metal only.
//
// Build and run: xcrun swiftc -O reflect_private.swift -o reflect_private && ./reflect_private > reflect_private.toml

import Foundation
import Metal

func q(_ s: String) -> String { "\"" + s.replacingOccurrences(of: "\"", with: "\\\"") + "\"" }
func fail(_ s: String) -> Never {
    FileHandle.standardError.write((s + "\n").data(using: .utf8)!)
    exit(1)
}

guard let device = MTLCreateSystemDefaultDevice() else { fail("no Metal device") }
let prelude = "#include <metal_stdlib>\nusing namespace metal;\n"

func lib(_ src: String) -> MTLLibrary {
    do { return try device.makeLibrary(source: prelude + src, options: MTLCompileOptions()) } catch {
        fail("compile: \(error)\n\(src)")
    }
}

/// The AIR the front end writes for `src`, as LLVM assembly.
func air(_ src: String) -> String {
    let dir = FileManager.default.temporaryDirectory.appendingPathComponent("reflect-private-\(getpid())")
    try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
    let file = dir.appendingPathComponent("m.metal")
    try! (prelude + src).write(to: file, atomically: true, encoding: .utf8)
    let p = Process()
    p.executableURL = URL(fileURLWithPath: "/usr/bin/xcrun")
    p.arguments = ["metal", "-S", "-emit-llvm", "-o", "-", file.path]
    let out = Pipe()
    p.standardOutput = out
    try! p.run()
    let data = out.fileHandleForReading.readDataToEndOfFile()
    p.waitUntilExit()
    return String(decoding: data, as: UTF8.self)
}

/// The AIR key of the argument record named `name`: the first `air.*` string of the metadata line that has
/// `!"air.arg_name", !"name"`.
func key(_ ll: String, _ name: String) -> String {
    for line in ll.split(separator: "\n") where line.contains("!\"air.arg_name\", !\"\(name)\"") {
        if let r = line.range(of: "!\"air\\.[a-z_]+\"", options: .regularExpression) {
            return String(line[r].dropFirst(2).dropLast())
        }
    }
    return "none"
}

func value(_ o: AnyObject, _ k: String) -> String {
    o.responds(to: NSSelectorFromString(k)) ? "\(o.value(forKey: k) ?? "nil")" : "no getter"
}

func builtins(_ list: [AnyObject], _ ll: String) {
    for a in list {
        let name = value(a, "name")
        print("[[case.builtin]]")
        print("name = \(q(name))")
        print("air = \(q(key(ll, name)))")
        for k in ["type", "access", "isActive", "index", "builtInType", "builtInDataType"] {
            print("\(k) = \(value(a, k))")
        }
    }
}

