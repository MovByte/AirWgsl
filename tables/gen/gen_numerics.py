#!/usr/bin/env python3
"""Generate tables/numerics.toml.

For every row of gen/numerics_rows.toml the MSL accuracy cells are read verbatim from
Tables 8.1 (precise single precision), 8.2 (fast single precision) and 8.3 (half
precision) in section 8.4 of the pinned MSL specification, and the WGSL cells from the
accuracy tables of WGSL section 15.7.4.1. Each cell becomes a quoted citation, so the
checker re-verifies it against the pinned texts. The comparison rules, the generic
decisions for precise math and half precision, and the questions of plan section 5.3
come from gen/numerics_rules.toml and gen/numerics_questions.toml.

Usage: gen_numerics.py --cache DIR [--out PATH]
"""

import argparse
import os
import sys
import tomllib

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import msltables  # noqa: E402
import specdoc  # noqa: E402
import tomlout  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
TABLES = os.path.dirname(HERE)
DECISIONS = {"native", "polyfill", "soft-float", "refusal"}


def wgsl_rows(doc):
    """{label: (f32 text, f16 text, row quote)} from the WGSL accuracy tables."""
    out = {}
    for t in doc.tables:
        sec = doc.section_at(t.offset)
        if not sec or sec["id"] != "concrete-float-accuracy":
            continue
        grid = t.grid()
        for raw, g in zip(t.rows[1:], grid[1:]):
            seen = []
            for c in raw:
                seen.append(specdoc.norm(c["text"]))
            label = g[0]["text"]
            out[label] = (g[1]["text"], g[2]["text"], " | ".join(seen))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cache", default=os.environ.get("TABLES_CACHE"))
    ap.add_argument("--out", default=os.path.join(TABLES, "numerics.toml"))
    a = ap.parse_args()
    sources = specdoc.load_sources()
    msl = specdoc.document("msl", sources, a.cache)
    wgsl = specdoc.document("wgsl", sources, a.cache)
    with open(os.path.join(HERE, "numerics_rows.toml"), "rb") as f:
        rows = tomllib.load(f)["row"]
    with open(os.path.join(HERE, "numerics_rules.toml"), "rb") as f:
        rules = tomllib.load(f)
    with open(os.path.join(HERE, "numerics_questions.toml"), "rb") as f:
        questions = tomllib.load(f).get("question", [])

    tables = {}
    for key, table in (("t81", "8.1"), ("t82", "8.2"), ("t83", "8.3")):
        labels = [r[key] for r in rows if key in r]
        # Table order is the specification's; sort the requested labels by their position.
        lines = msltables.table_lines(msl, table)
        def pos(label):
            import re
            pat = re.compile(r"^%s(\s|$)" % re.escape(label))
            for i, line in enumerate(lines):
                if pat.match(line):
                    return i
            raise SystemExit("MSL table %s has no row %r" % (table, label))
        ordered = sorted(set(labels), key=pos)
        tables[key] = msltables.rows(msl, table, ordered)
    wrows = wgsl_rows(wgsl)

    generic = rules["generic"]
    out_rows = []
    for r in rows:
        if r["fast_f32"] not in DECISIONS:
            raise SystemExit("%s: unknown decision %r" % (r["id"], r["fast_f32"]))
        row = {"id": r["id"], "msl": r["msl"]}
        cites = [r["def"]]
        for key, col, table in (("t81", "msl_precise_f32", "8.1"), ("t82", "msl_fast_f32", "8.2"),
                                ("t83", "msl_half_from_apple4", "8.3")):
            if key in r:
                text = tables[key][r[key]]
                row[col] = text
                cites.append({"src": "msl", "ref": "8.4", "quote": text})
            elif key == "t82" and "t81" not in r:
                row[col] = "not stated in MSL 8.4"
        if "wgsl" in r:
            if r["wgsl"] not in wrows:
                raise SystemExit("%s: WGSL accuracy table has no row %r" % (r["id"], r["wgsl"]))
            f32, f16, quote = wrows[r["wgsl"]]
            row["wgsl"] = r["wgsl"]
            row["wgsl_f32"] = f32
            row["wgsl_f16"] = f16
            cites.append({"src": "wgsl", "ref": "#concrete-float-accuracy", "quote": quote})
        else:
            row["wgsl"] = "none"
        if "wgsl_def" in r:
            cites.append(r["wgsl_def"])
        row["fast_f32"] = r["fast_f32"]
        row["fast_f32_analysis"] = r["fast_f32_analysis"]
        row["precise_f32"] = generic["precise_f32"]
        row["precise_f32_analysis"] = generic["precise_f32_analysis"]
        row["half"] = generic["half"]
        row["half_analysis"] = generic["half_analysis"]
        row["cite"] = cites
        out_rows.append(row)

    parts = [
        "# Generated by tables/gen/gen_numerics.py from the sources pinned in tables/sources.toml\n"
        "# and tables/gen/numerics_{rows,rules,questions}.toml. Do not edit by hand.\n",
        tomlout.table("meta", {
            "msl": "%s %s (%s), %s" % (sources["msl"]["title"], sources["msl"]["version"],
                                       sources["msl"]["date"], sources["msl"]["url"]),
            "wgsl": "%s, %s %s, %s" % (sources["wgsl"]["title"], sources["wgsl"]["version"],
                                       sources["wgsl"]["date"], sources["wgsl"]["url"]),
            "cells": "msl_* and wgsl_* cells are the specification table text verbatim; superscripts are lost in the PDF text, so 2-126 reads 2^-126",
            "decisions": "native, polyfill, soft-float or refusal, under the rules in [[rule]]",
        }),
    ]
    for rule in rules["rule"]:
        parts.append(tomlout.array_item("rule", rule))
    parts.append(tomlout.array_item("generic", dict(generic, id="generic-decisions")))
    for r in out_rows:
        parts.append(tomlout.array_item("row", r))
    for q in questions:
        parts.append(tomlout.array_item("question", q))
    with open(a.out, "w") as f:
        f.write("\n".join(parts))
    print("wrote %s (%d rows)" % (a.out, len(out_rows)))


if __name__ == "__main__":
    main()
