#!/usr/bin/env python3
"""Generate src/num/wgsl/xfconst.wgsl: the constants and polynomial kernels of the extended-precision library.

Every value is computed here from its definition with exact integer and rational arithmetic (no stored digits):
pi from Machin's formula, ln 2 and ln(5/4) from the atanh series, atan(k/8) from Euler's series, the Taylor
coefficients as exact rationals (the tanh coefficients from the recurrence (2k+1) a_k = [k = 0] - sum a_i a_j that
tanh' = 1 - tanh^2 gives). Each constant is rounded to the nearest 64-bit significand of the nm_xf format.

Usage: gen_consts.py > src/num/wgsl/xfconst.wgsl
"""

from fractions import Fraction
import sys

PREC = 1024  # bits of the fixed-point computations
ONE = 1 << PREC


def fx(fr):
    """A Fraction as fixed point, rounded to nearest."""
    return (fr.numerator * ONE * 2 + fr.denominator) // (2 * fr.denominator)


def atanh_inv(n):
    """atanh(1/n) in fixed point, for an integer n > 1."""
    total = 0
    k = 0
    power = ONE // n  # (1/n)^(2k+1)
    n2 = n * n
    while power:
        total += power // (2 * k + 1)
        power //= n2
        k += 1
    return total


def atan_inv(n):
    """atan(1/n) in fixed point."""
    total = 0
    k = 0
    power = ONE // n
    n2 = n * n
    while power:
        term = power // (2 * k + 1)
        total += term if k % 2 == 0 else -term
        power //= n2
        k += 1
    return total


PI = 16 * atan_inv(5) - 4 * atan_inv(239)
LN2 = 2 * atanh_inv(3)
LN10 = 3 * LN2 + 2 * atanh_inv(9)  # ln 10 = 3 ln 2 + ln(5/4), ln(5/4) = 2 atanh(1/9)


def atan_rational(p, q):
    """atan(p/q) in fixed point by Euler's series sum (2^2n (n!)^2 / (2n+1)!) x^(2n+1) / (1 + x^2)^(n+1)."""
    if p == 0:
        return 0
    x2 = Fraction(p * p, q * q)
    ratio = x2 / (1 + x2)
    term = fx(Fraction(p, q) / (1 + x2))
    total = 0
    n = 0
    while term:
        total += term
        n += 1
        term = term * (2 * n) * ratio.numerator // ((2 * n + 1) * ratio.denominator)
    return total


def div_fx(a, b):
    return (a * ONE * 2 + b) // (2 * b)


def xf(value_fx):
    """A fixed-point value as an nm_xf constructor: 64-bit significand rounded to nearest, exponent, sign."""
    if value_fx == 0:
        return "nm_xf(vec2<u32>(0u, 0u), 0, 0u)"
    s = 1 if value_fx < 0 else 0
    v = abs(value_fx)
    nbits = v.bit_length()
    e = nbits - 1 - PREC  # value = v * 2^-PREC, leading one at 2^e
    shift = nbits - 64
    m = (v + (1 << (shift - 1))) >> shift if shift > 0 else v << -shift
    if m >> 64:
        m >>= 1
        e += 1
    return "nm_xf(vec2<u32>(0x%08xu, 0x%08xu), %d, %du)" % (m & 0xffffffff, m >> 32, e, s)


def xf_frac(fr):
    return xf(fx(fr))


def factorial(n):
    r = 1
    for k in range(2, n + 1):
        r *= k
    return r


def tanh_coefficients(count):
    a = []
    for k in range(count):
        acc = Fraction(1 if k == 0 else 0)
        for i in range(k):
            j = k - 1 - i
            acc -= a[i] * a[j]
        a.append(acc / (2 * k + 1))
    return a


def horner(name, doc, coefficients):
    """fn name(u) = sum coefficients[k] * u^k, by Horner's rule."""
    lines = ["// %s" % line for line in doc]
    lines.append("fn %s(u: nm_xf) -> nm_xf {" % name)
    lines.append("    var p = %s;" % xf_frac(coefficients[-1]))
    for c in reversed(coefficients[:-1]):
        lines.append("    p = nm_xf_add(nm_xf_mul(p, u), %s);" % xf_frac(c))
    lines.append("    return p;")
    lines.append("}")
    return "\n".join(lines)


def const(name, doc, value_fx):
    return "// %s\nconst %s = %s;" % (doc, name, xf(value_fx))


def main():
    out = []
    out.append("// Generated by src/num/gen_consts.py. Do not edit by hand.")
    out.append("//")
    out.append("// Constants and polynomial kernels of the extended-precision library (xf.wgsl), each rounded to the")
    out.append("// nearest 64-bit significand.")
    out.append("")
    out.append(const("nm_xf_pi", "pi", PI))
    out.append(const("nm_xf_pi_2", "pi / 2", PI // 2))
    out.append(const("nm_xf_pi_4", "pi / 4", PI // 4))
    out.append(const("nm_xf_3pi_4", "3 pi / 4", 3 * PI // 4))
    out.append(const("nm_xf_ln2", "ln 2", LN2))
    out.append(const("nm_xf_log2e", "log2(e) = 1 / ln 2", div_fx(ONE, LN2)))
    out.append(const("nm_xf_log2_10", "log2(10) = ln 10 / ln 2", div_fx(LN10, LN2)))
    out.append(const("nm_xf_ln10_inv", "log10(e) = 1 / ln 10", div_fx(ONE, LN10)))
    out.append(const("nm_xf_log10_2", "log10(2) = ln 2 / ln 10", div_fx(LN2, LN10)))
    # 2/pi as 32-bit words of its binary fraction, most significant first.
    two_over_pi = div_fx(2 * ONE, PI)
    words = []
    for j in range(10):
        words.append((two_over_pi >> (PREC - 32 * (j + 1))) & 0xffffffff)
    out.append("")
    out.append("// Word j of the binary fraction of 2 / pi: bits 2^-(32j+1) .. 2^-(32j+32).")
    out.append("fn nm_twobypi_word(j: u32) -> u32 {")
    out.append("    switch (j) {")
    for j, w in enumerate(words):
        out.append("        case %du: {\n            return 0x%08xu;\n        }" % (j, w))
    out.append("        default: {\n            return 0u;\n        }")
    out.append("    }")
    out.append("}")
    out.append("")
    out.append("// atan(k / 8) for k = 0 .. 8.")
    out.append("fn nm_xf_atan_tab(k: u32) -> nm_xf {")
    out.append("    switch (k) {")
    for k in range(8):
        out.append("        case %du: {\n            return %s;\n        }" % (k, xf(atan_rational(k, 8))))
    out.append("        default: {\n            return %s;\n        }" % xf(PI // 4))
    out.append("    }")
    out.append("}")
    out.append("")
    # e^t = sum t^n / n!, |t| <= ln(2)/2 + 2^-60: the first omitted term is below 2^-74 relative.
    out.append(horner("nm_xf_poly_exp", ["e^u, Taylor terms n = 0 .. 17 (|u| <= 0.35)."],
                      [Fraction(1, factorial(n)) for n in range(18)]))
    out.append("")
    # atanh(t)/t = sum u^k / (2k+1), u = t^2 <= 0.0295 (|t| <= 3 - 2 sqrt 2): omitted terms below 2^-76.
    out.append(horner("nm_xf_poly_atanh", ["atanh(t) / t as a series in u = t^2, terms k = 0 .. 13 (u <= 0.0295)."],
                      [Fraction(1, 2 * k + 1) for k in range(14)]))
    out.append("")
    # atan(t)/t = sum (-1)^k u^k / (2k+1), u = t^2 <= 1/256: omitted terms below 2^-80.
    out.append(horner("nm_xf_poly_atan", ["atan(t) / t as a series in u = t^2, terms k = 0 .. 9 (u <= 1/256)."],
                      [Fraction((-1) ** k, 2 * k + 1) for k in range(10)]))
    out.append("")
    # sin(x)/x = sum (-1)^k u^k / (2k+1)!, u = x^2 <= (pi/4)^2: omitted terms below 2^-75.
    out.append(horner("nm_xf_poly_sin", ["sin(x) / x as a series in u = x^2, terms k = 0 .. 11 (u <= (pi/4)^2)."],
                      [Fraction((-1) ** k, factorial(2 * k + 1)) for k in range(12)]))
    out.append("")
    out.append(horner("nm_xf_poly_cos", ["cos(x) as a series in u = x^2, terms k = 0 .. 12 (u <= (pi/4)^2)."],
                      [Fraction((-1) ** k, factorial(2 * k)) for k in range(13)]))
    out.append("")
    # sinh(x)/x = sum u^k / (2k+1)!, u = x^2 <= 1: omitted terms below 2^-77.
    out.append(horner("nm_xf_poly_sinh", ["sinh(x) / x as a series in u = x^2, terms k = 0 .. 12 (u <= 1)."],
                      [Fraction(1, factorial(2 * k + 1)) for k in range(13)]))
    out.append("")
    # tanh(x)/x for u = x^2 <= 2^-12: omitted terms below 2^-90.
    out.append(horner("nm_xf_poly_tanh", ["tanh(x) / x as a series in u = x^2, terms k = 0 .. 7 (u <= 2^-12)."],
                      tanh_coefficients(8)))
    out.append("")
    # (e^t - 1)/t = sum t^n / (n+1)!, |t| <= 2^-4: omitted terms below 2^-80.
    out.append(horner("nm_xf_poly_expm1", ["(e^u - 1) / u, Taylor terms n = 0 .. 16 (|u| <= 2^-4)."],
                      [Fraction(1, factorial(n + 1)) for n in range(17)]))
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
